import {expect,test} from '@playwright/test';
test('home, calendar and research remain usable on a narrow screen',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.getByRole('button',{name:'Replay 2023 data'}).click();
  await page.getByRole('combobox',{name:'From',exact:true}).selectOption('Mumbai');
  await page.getByRole('combobox',{name:'To',exact:true}).selectOption('Delhi');
  await page.getByRole('button',{name:'Estimate fares'}).click();
  await expect(page.getByText('Lowest estimate',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Explore',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Explore fares'})).toBeVisible();
  await page.getByRole('button',{name:'Mumbai airport'}).click();
  await expect(page.getByRole('button',{name:/Origin · Mumbai/})).toBeVisible();
  await page.getByRole('button',{name:'Week',exact:true}).click();
  const day=page.getByLabel('Departure dates').getByRole('button').first();
  const minimum=await day.locator('span').innerText();
  await day.click();
  await expect(page.getByRole('heading',{name:'Price comparison'}).locator('..').locator('..').getByText(minimum,{exact:true})).toBeVisible();
  await expect(page.getByText('Historical search · no archived quote')).toBeVisible();
  await expect(page.getByRole('link',{name:'Check on Google Flights'})).toHaveCount(0);
  await expect(page.getByLabel('Observed Google Flights fare')).toBeEmpty();
  await expect(page.getByText('Estimate minus observed fare')).toHaveCount(0);
  await page.getByRole('button',{name:'Day',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Departure date fares'})).toBeVisible();
  await page.getByRole('link',{name:'Research',exact:true}).click();
  await page.getByRole('button',{name:'Random example'}).click();
  await expect(page.getByRole('combobox',{name:'Held-out example',exact:true})).toHaveValue('random');
  await expect(page.getByText('Recorded dataset fare',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Predict and reveal'}).click();
  await expect(page.getByText('Recorded dataset fare',{exact:true})).toBeVisible();
  await expect(page.getByText(/L7 Random Forest · Held-out interpolation · Example/)).toBeVisible();
  await page.getByRole('link',{name:'Home',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'From',exact:true})).toHaveValue('Mumbai');
  await expect(page.getByRole('combobox',{name:'To',exact:true})).toHaveValue('Delhi');
  await expect(page.getByLabel('Departure date')).toHaveValue('2023-01-23');
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});

